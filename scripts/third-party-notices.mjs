#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md: the license of every runtime npm package
// bundled into the extension, copied from node_modules. Those licenses keep
// applying to that code. Run after changing dependencies; it fails on a
// package whose license it cannot find or on a copyleft license, which Wera
// must not ship.
//
// Usage: node scripts/third-party-notices.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
const packages = lock.packages ?? {};

const runtime = [];
for (const [pkgPath, meta] of Object.entries(packages)) {
  if (!pkgPath.startsWith('node_modules/')) continue;
  if (meta.dev || meta.devOptional) continue;
  const name = pkgPath.slice('node_modules/'.length).replace(/^.*node_modules\//, '');
  runtime.push({ pkgPath, name, version: meta.version ?? '' });
}

const seen = new Map();
for (const item of runtime) {
  const key = `${item.name}@${item.version}`;
  if (!seen.has(key)) seen.set(key, item);
}
const sorted = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const findFile = (dir, re) => {
  if (!existsSync(dir)) return null;
  const hit = readdirSync(dir)
    .filter((f) => re.test(f))
    .sort()[0];
  return hit ? join(dir, hit) : null;
};

const lines = [
  '# Third-party notices',
  '',
  "Wera's own code is proprietary (see LICENSE). Its built bundle includes the",
  'open-source packages below, each under its own license, reproduced here.',
  'Generated by `node scripts/third-party-notices.mjs`; do not edit by hand.',
  '',
];

for (const { pkgPath, name, version } of sorted) {
  const licFile = findFile(pkgPath, /^(licen[cs]e|copying)(\..+)?$/i);
  if (!licFile) {
    console.error(`no license file for ${name} ${version} (${pkgPath})`);
    process.exit(1);
  }
  const text = readFileSync(licFile, 'utf8').trimEnd();
  if (/GNU (AFFERO |LESSER )?GENERAL PUBLIC LICENSE/i.test(text)) {
    console.error(`copyleft license in ${name} ${version}: ${licFile}`);
    process.exit(1);
  }
  lines.push(`## ${name} ${version}`, '', '```', text, '```', '');
  const noticeFile = findFile(pkgPath, /^notice(\..+)?$/i);
  if (noticeFile) {
    lines.push('```', readFileSync(noticeFile, 'utf8').trimEnd(), '```', '');
  }
}

writeFileSync('THIRD_PARTY_NOTICES.md', lines.join('\n') + '\n');
console.log(`wrote THIRD_PARTY_NOTICES.md (${sorted.length} packages)`);
